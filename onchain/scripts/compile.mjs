import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const names = [
  "ECnySim",
  "MerchantRegistry",
  "LicenceRegistry",
  "AuditAnchor",
  "AgentWallet",
];
assert.match(solc.version(), /^0\.8\.11\+/, "Use pinned solc 0.8.11");

const sources = Object.fromEntries(
  names.map((name) => [
    `${name}.sol`,
    { content: readFileSync(join(root, "src", `${name}.sol`), "utf8") },
  ]),
);
const input = {
  language: "Solidity",
  sources,
  settings: {
    evmVersion: "london",
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
for (const diagnostic of output.errors ?? []) {
  if (diagnostic.severity === "error")
    throw new Error(diagnostic.formattedMessage);
}
const artifactDir = join(root, "artifacts");
const generatedPath = resolve(root, "../packages/chain/src/generated/abis.ts");
mkdirSync(artifactDir, { recursive: true });
mkdirSync(dirname(generatedPath), { recursive: true });
let generated =
  "// Generated by onchain/scripts/compile.mjs. Do not edit manually.\n";
for (const name of names) {
  const contract = output.contracts?.[`${name}.sol`]?.[name];
  assert.ok(contract?.evm?.bytecode?.object, `Missing bytecode for ${name}`);
  const artifact = {
    contractName: name,
    compiler: solc.version(),
    evmVersion: "london",
    abi: contract.abi,
    bytecode: `0x${contract.evm.bytecode.object}`,
  };
  writeFileSync(
    join(artifactDir, `${name}.json`),
    `${JSON.stringify(artifact, null, 2)}\n`,
  );
  generated += `export const ${name}Abi = ${JSON.stringify(contract.abi, null, 2)} as const;\n\n`;
}
writeFileSync(generatedPath, generated);
execFileSync(resolve(root, "../node_modules/.bin/biome"), [
  "format",
  "--write",
  generatedPath,
]);
console.log(
  `Compiled ${names.length} contracts with ${solc.version()} for london`,
);
